#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
gen_anim_c.py —— 把 anim_frames 渲染的帧写成固件用的 C 文件

单独成文件，避免和 anim_frames.py 的转义问题纠缠。
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import anim_frames as A
import mcstream

NL = "\n"
STATE_ORDER = ["IDLE", "WALK", "RUN", "ATTACK", "JUMP", "SNEAK", "SLEEP"]


def main():
    HERE = os.path.dirname(os.path.abspath(__file__))
    out_dir = os.path.join(HERE, "..", "例程_ST7735", "示例代码", "BSP", "SKIN")

    print("渲染所有帧 ...")
    frames, (fw, fh) = A.build_frames()

    blobs = []
    for st in STATE_ORDER:
        for i, img in enumerate(frames[st]):
            enc = mcstream.rle_encode(A.to565(img))
            blobs.append((st, i, enc))
    total = sum(len(e) for _, _, e in blobs)
    print(f"帧尺寸 {fw}x{fh}  共 {len(blobs)} 帧  RLE {total/1024:.0f} KB")

    # ---------- 头文件 ----------
    h = os.path.join(out_dir, "skin_anim.h")
    with open(h, "w", encoding="utf-8", newline=NL) as f:
        f.write("/* auto-generated by tools/gen_anim_c.py -- do not edit */" + NL)
        f.write("#ifndef __SKIN_ANIM_H" + NL)
        f.write("#define __SKIN_ANIM_H" + NL + NL)
        f.write("#include <stdint.h>" + NL + NL)
        f.write("#define ANIM_W      %d" % fw + NL)
        f.write("#define ANIM_H      %d" % fh + NL)
        f.write("#define ANIM_FRAMES %d" % A.FRAMES + NL)
        f.write("#define ANIM_STATES %d" % len(STATE_ORDER) + NL + NL)
        f.write("typedef struct {" + NL)
        f.write("    const uint8_t *data;" + NL)
        f.write("    uint16_t       len;" + NL)
        f.write("} AnimFrame_t;" + NL + NL)
        f.write("extern const AnimFrame_t g_anim[ANIM_STATES][ANIM_FRAMES];" + NL + NL)
        f.write("#endif" + NL)

    # ---------- C 文件 ----------
    c = os.path.join(out_dir, "skin_anim.c")
    with open(c, "w", encoding="utf-8", newline=NL) as f:
        f.write("/* auto-generated by tools/gen_anim_c.py -- do not edit */" + NL)
        f.write('#include "skin_anim.h"' + NL + NL)
        for st, i, enc in blobs:
            name = "anim_%s_%d" % (st.lower(), i)
            f.write("static const uint8_t %s[%d] = {" % (name, len(enc)) + NL)
            for k in range(0, len(enc), 20):
                part = enc[k:k + 20]
                f.write("    " + ",".join("0x%02X" % b for b in part) + "," + NL)
            f.write("};" + NL + NL)
        f.write("const AnimFrame_t g_anim[ANIM_STATES][ANIM_FRAMES] = {" + NL)
        for st in STATE_ORDER:
            f.write("    {   /* %s */" % st + NL)
            for i in range(A.FRAMES):
                name = "anim_%s_%d" % (st.lower(), i)
                ln = [len(e) for s2, i2, e in blobs if s2 == st and i2 == i][0]
                f.write("        { %s, %d }," % (name, ln) + NL)
            f.write("    }," + NL)
        f.write("};" + NL)

    print("生成:", h)
    print("生成:", c)


if __name__ == "__main__":
    main()
