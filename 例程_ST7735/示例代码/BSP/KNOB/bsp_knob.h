/**==================================================================================================================
 **【文件名称】  bsp_knob.h
 **【功能】      机械旋钮 / 按键 / 蜂鸣器 驱动（阶段 1 自测用）
 **【硬件】      魔女 STM32F407VET6 核心板
 **【接线】
 **    EC11 编码器模块   VCC->3.3V  GND->GND   A(CLK)->PC6   B(DT)->PC7   SW->PC0
 **    确认键模块        VCC->3.3V  GND->GND   OUT->PE2
 **    返回键模块        VCC->3.3V  GND->GND   OUT->PE3
 **    蜂鸣器模块(有源)  VCC->3.3V  GND->GND   IO->PC9
 **【说明】      PC6/PC7 = TIM8_CH1/CH2，硬件编码器模式，不占 CPU、不丢步
 **              按键为"模块输出高电平有效"，20ms 软件消抖
 **              蜂鸣器按【有源】模块写（IO 拉高即响）；若买的是无源，见 bsp_knob.c 里的宏
====================================================================================================================*/
#ifndef __BSP_KNOB_H
#define __BSP_KNOB_H

#include "stm32f4xx.h"

/* ------------------------------------------------------------------
 * 按键编号，给 Key_GetPress() / Key_IsDown() 用
 * ------------------------------------------------------------------ */
#define KEY_ID_SW     0   /* 编码器轴按下 -> PC0 */
#define KEY_ID_OK     1   /* 确认键       -> PE2 */
#define KEY_ID_BACK   2   /* 返回键       -> PE3 */
#define KEY_ID_NUM    3


/* ------------------------------------------------------------------
 * 初始化
 * ------------------------------------------------------------------ */
void    Knob_Init(void);        /* 编码器(TIM8) + 3 个按键 + 蜂鸣器，一次全初始化 */


/* ------------------------------------------------------------------
 * 编码器
 *   Knob_GetDelta(): 取走"上次调用以来"的计数增量
 *     返回 >0 表示顺时针，<0 表示逆时针，0 表示没动
 *     内部已做 16 位回绕处理，可放心连续调用
 * ------------------------------------------------------------------ */
int16_t Knob_GetDelta(void);
int32_t Knob_GetTotal(void);    /* 累计计数（从开机起），调试用 */


/* ------------------------------------------------------------------
 * 按键
 *   Key_Scan10ms(): 每 10ms 必须调用一次（在主循环里用 Delay_ms(10) 兜住）
 *   Key_GetPress(): 返回 1 表示"本次新按下"（读一次就清掉，不会重复触发）
 *   Key_IsDown():   返回 1 表示"当前正按着"（做长按用）
 * ------------------------------------------------------------------ */
void    Key_Scan10ms(void);
uint8_t Key_GetPress(uint8_t id);
uint8_t Key_IsDown(uint8_t id);


/* ------------------------------------------------------------------
 * 蜂鸣器
 * ------------------------------------------------------------------ */
void    BZ_On(void);
void    BZ_Off(void);
void    BZ_Beep(uint16_t ms);   /* 响 ms 毫秒后自动关（阻塞式，阶段 1 够用） */


/* ------------------------------------------------------------------
 * 延时（DWT 周期计数器，不占中断、不依赖 -O3 优化等级）
 * ------------------------------------------------------------------ */
void    Delay_Init(void);
void    Delay_ms(uint32_t ms);
void    Delay_us(uint32_t us);

#endif /* __BSP_KNOB_H */
